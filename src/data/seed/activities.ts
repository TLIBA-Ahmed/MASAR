export function createActivities(): ActivityTemplate[] {
  return catalogue.map(([ar, fr, category, skills, duration, format, materials], i) => ({
    id: `ACT-${String(i + 1).padStart(3, '0')}`,
    title: bi(ar, fr),
    description: bi(
      `نشاط «${ar}» لدعم المهارات التربوية في مساحة آمنة ومشجّعة، وفق اختيار الطفل وتقدير المربي.`,
      `L’activité « ${fr} » soutient les compétences éducatives dans un cadre bienveillant, avec l’accord du participant et l’accompagnement de l’éducateur.`,
    ),
    category,
    skills,
    minAge: category === 'vocational' ? 14 : 8,
    maxAge: 17,
    duration,
    minParticipants: format === 'group' ? 3 : 1,
    maxParticipants: format === 'group' ? 8 : 1,
    format,
    materials,
    instructions: [
      bi(
        'تهيئة المكان، تقديم الهدف والتحقق من موافقة المشاركين.',
        'Préparer l’espace, expliquer l’objectif et recueillir l’accord des participants.',
      ),
      bi(
        `تقديم «${ar}» تدريجياً، مع مثال بسيط وفترة تجربة.`,
        `Présenter « ${fr} » progressivement avec un exemple et un temps d’essai.`,
      ),
      bi(
        'مرافقة الإنجاز دون إصدار أحكام وإتاحة فترات استراحة.',
        'Accompagner la réalisation sans jugement et proposer des pauses.',
      ),
      bi(
        'تبادل الانطباعات وتوثيق المشاركة والتقدم الملاحظ.',
        'Recueillir les impressions et documenter la participation et les progrès observés.',
      ),
    ],
    adaptations: bi(
      'تقليل عدد الخطوات أو المدة، إتاحة دعم فردي وبدائل للتعبير.',
      'Réduire les étapes ou la durée ; proposer un soutien individuel et d’autres modes d’expression.',
    ),
    evaluation: bi(
      'ملاحظات نوعية مرتبطة بالأهداف، يحرّرها المربي بعد الحصة.',
      'Observations qualitatives liées aux objectifs, rédigées par l’éducateur après la séance.',
    ),
    conditions: bi(
      'موافقة الطفل، إشراف مهني، تكييف النشاط والتحقق من ملاءمة المعدات.',
      'Accord du participant, supervision professionnelle et vérification de l’adéquation du matériel.',
    ),
    source: bi(
      'مثال اصطناعي للتجربة — ليس من Kit ADO',
      'Exemple synthétique — ne provient pas du Kit ADO',
    ),
    validation: 'example',
    favorite: i < 3,
    createdAt: '2026-10-01',
  }));
}
