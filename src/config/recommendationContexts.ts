import { bi } from '../types';
import type { RecommendationContext, RecommendationStrategy, ResourceKind, Role } from '../types';

function context(
  contextId: string,
  labelAr: string,
  labelFr: string,
  icon: string,
  allowedRoles: Role[],
  recommendationStrategy: RecommendationStrategy,
  domainAttribute: string,
  sources: ResourceKind[],
  overrides: Partial<RecommendationContext> = {},
): RecommendationContext {
  return {
    contextId,
    labelAr,
    labelFr,
    icon,
    allowedRoles,
    description: bi(
      'اقتراحات قابلة للتفسير يراجعها المهني قبل أي تنفيذ.',
      'Des propositions explicables à examiner avant toute mise en œuvre.',
    ),
    requiredPermissions: [
      'recommendation.use',
      'recommendation.validate',
      ...sources.map((s): `${ResourceKind}.read` => `${s}.read`),
    ],
    attributeConditions: [
      { attribute: 'canRecommend', equals: true },
      { attribute: domainAttribute, equals: true },
    ],
    requiredInputs: ['caseId', 'goalIds'],
    optionalInputs: ['request', 'constraints'],
    authorizedDataSources: sources,
    recommendationStrategy,
    outputSchema: 'resource-proposals',
    ...overrides,
  };
}

